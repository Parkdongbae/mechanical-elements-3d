/** 상태(닫힌 식): θ = 0.8·t, D 높이 d = 0.2·(1−cos θ), 롤러 |x| = 0.3375 + 0.4·d */
export interface State252 {
  theta: number;
  d: number;
  xRoll: number;
}

export function state252(t: number): State252 {
  const theta = K252.OMEGA * t;
  const d = K252.CRANK_R * (1 - Math.cos(theta)); // CRANK_R = TB/2
  return { theta, d, xRoll: K252.X0 + 0.4 * d }; // 0.4 = 팔 홈 기울기(tan 21.8°)
}

/** D 판(구멍 3: 팔 홈 2 + 덩이 홈) + 막대 + 글자판 'D'. 원점 = 세계, 모델이 y = d 로 옮긴다 */
export function frameD252(): THREE.Group {
  const g = new THREE.Group();
  g.name = 'frameD';
  // 판: z −0.14~−0.08, 홈 3 개
  const sh = shapeFrom(FRAMED252);
  const S = K252.SLOT_W;
  sh.holes.push(stadiumShape(-0.8975, 1.2, -0.3135, 2.66, S)); // 왼팔 홈
  sh.holes.push(stadiumShape(0.3135, 2.66, 0.8975, 1.2, S)); // 오른팔 홈(거울)
  sh.holes.push(stadiumShape(-0.24, 0.91, 0.24, 0.91, 0.032)); // 덩이 홈(크랭크 핀, 반폭 0.032)
  const plate = mesh(extrude(sh, 0.06, 0.004), steel());
  plate.name = 'plateD';
  plate.position.z = -0.11;
  g.add(plate);
  // 막대: r 0.04, y 0.20~0.80, z −0.11 — 안내 통 구멍(0.041)을 지나고 D 판과 함께 오르내림
  const rodD = mesh(lathe(rodProfile(0.04, 0.2, 0.8, 0.005, 0.005), 24), steel());
  rodD.name = 'rodD';
  rodD.position.set(0, 0, -0.11);
  g.add(rodD);
  // 글자판 'D': 줄기 + 오른쪽 반원 띠, z −0.08~−0.078, 덩이 앞면 (0.16, 0.95)
  const ink = paint(0x22262b);
  const stem = mesh(new THREE.BoxGeometry(0.014, 0.09, 0.002), ink);
  stem.position.set(0.141, 0.95, -0.079);
  const bowl = mesh(extrude(annularSector(0.031, 0.045, -Math.PI / 2, Math.PI / 2), 0.002), ink);
  bowl.position.set(0.141, 0.95, -0.079);
  g.add(stem, bowl);
  setMM(g, { kind: 'frame' });
  return g;
}
