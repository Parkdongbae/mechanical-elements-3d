const clamp01 = (x: number): number => Math.min(1, Math.max(0, x));
const sm = (x: number): number => {
  const c = clamp01(x);
  return c * c * (3 - 2 * c);
};

/** 폴 i 의 각(도): 0.5° 간격 표 + 마지막 점까지 보간, 그 너머는 마지막 값 */
export function table240(i: number, phi: number): number {
  const tab = TABS[i]!;
  const [lp, lv] = LAST[i]!;
  const p = Math.max(0, phi);
  if (p >= lp) return lv;
  const nLast = tab.length - 1;
  const x0 = nLast * 0.5;
  if (p >= x0) return tab[nLast]! + (lv - tab[nLast]!) * ((p - x0) / (lp - x0));
  const f = p / 0.5;
  const k = Math.floor(f);
  return tab[k]! + (tab[k + 1]! - tab[k]!) * (f - k);
}

export interface State240 {
  theta: number;
  thetaMax: number;
  lam: [number, number, number];
  sigma: number;
  phase: 'turn' | 'back' | 'hold';
  u: number;
  n: number;
  catchers: number[];
}

/** 240번 운동식(t = 장면 시간 초) */
export function state240(t: number): State240 {
  const n = Math.floor(t / K.Tb);
  const u = t - n * K.Tb;
  let theta: number;
  let thetaMax: number;
  let phase: 'turn' | 'back' | 'hold';
  if (u < 1.0) {
    const a = 12.5 * sm(u / 1.0);
    theta = 9 * n + a;
    thetaMax = 9 * n + Math.max(3.5, a);
    phase = 'turn';
  } else if (u < 1.3) {
    theta = 9 * n + 12.5 - 3.5 * sm((u - 1.0) / 0.3);
    thetaMax = 9 * n + 12.5;
    phase = 'back';
  } else {
    theta = 9 * (n + 1);
    thetaMax = 9 * n + 12.5;
    phase = 'hold';
  }
  const lam: number[] = [];
  for (let i = 0; i < 3; i++) {
    const m = Math.floor((thetaMax - K.lk[i]! - K.dk[i]!) / 18) + 1;
    const phi = Math.max(0, theta - K.lk[i]! - 18 * m);
    lam.push(table240(i, phi));
  }
  const sigma = K.sig[0]! + K.sig[1]! * lam[2]! + K.sig[2]! * lam[2]! * lam[2]!;
  const catchers = phase !== 'hold' ? [] : (n + 1) % 2 === 0 ? [0, 1] : [2];
  return { theta, thetaMax, lam: [lam[0]!, lam[1]!, lam[2]!], sigma, phase, u, n, catchers };
}
